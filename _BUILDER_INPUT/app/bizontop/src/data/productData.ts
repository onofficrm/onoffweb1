export function getProductById(id: string): ProductDetail | undefined {
  // Direct match
  if (PRODUCT_DETAILS[id]) {
    return PRODUCT_DETAILS[id];
  }
  // Alias checks for backward compatibility
  const aliasMap: Record<string, string> = {
    'facility-capital': 'facility',
    'lab': 'research-center',
    'rnd-dept': 'research-department',
    'corporation': 'incorporation',
    'advisory': 'integrated',
  };
  if (aliasMap[id] && PRODUCT_DETAILS[aliasMap[id]]) {
    return PRODUCT_DETAILS[aliasMap[id]];
  }
  return undefined;
}

export function getCategoryById(categoryId: string): CategoryDetail | undefined {
  if (categoryId === 'policy-fund') {
    return CATEGORY_DETAILS['funding'];
  }
  return CATEGORY_DETAILS[categoryId];
}

export function getAllProducts(): ProductDetail[] {
  return Object.values(PRODUCT_DETAILS);
}

export function getProductsByCategory(category: string): ProductDetail[] {
  const cat = category === 'policy-fund' ? 'funding' : category;
  return Object.values(PRODUCT_DETAILS).filter((p) => p.category === cat);
}
